create table if not exists public.traffic_results (
    id bigint generated by default as identity primary key,
    upload_id uuid not null,
    direction text not null check (direction in ('north', 'south', 'east', 'west')),
    vehicle_count integer not null default 0 check (vehicle_count >= 0),
    emergency_count integer not null default 0 check (emergency_count >= 0),
    density double precision not null check (density >= 0),
    congestion_level text not null,
    green_time_seconds integer not null default 0 check (green_time_seconds >= 0),
    created_at timestamptz not null default timezone('utc', now())
);

create index if not exists traffic_results_upload_id_idx
    on public.traffic_results (upload_id);

create index if not exists traffic_results_created_at_idx
    on public.traffic_results (created_at desc);

alter table public.traffic_results enable row level security;
